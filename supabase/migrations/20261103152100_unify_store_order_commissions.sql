create or replace function private.recalculate_request_item_commission(p_request_item_id uuid)
returns void language plpgsql security definer set search_path to 'public','private','pg_temp' as $function$
declare v_line numeric; v_rate numeric(5,2); v_returned numeric;
begin
  select i.line_total,c.rate into v_line,v_rate from public.store_order_request_items i
    join public.commissions c on c.store_order_request_item_id=i.id
    where i.id=p_request_item_id and c.status in ('pending','payable');
  if not found then return; end if;
  select least(v_line,coalesce(sum(case when a.quantity>0 then least(a.quantity,i.quantity)*i.unit_price else a.amount end),0))
    into v_returned from public.store_order_request_items i
    left join public.store_order_item_adjustments a on a.request_item_id=i.id and a.status='completed'
    where i.id=p_request_item_id;
  update public.commissions set amount=round(greatest(v_line-coalesce(v_returned,0),0)*v_rate/100,2),updated_at=now()
    where store_order_request_item_id=p_request_item_id and status in ('pending','payable');
end;$function$;

