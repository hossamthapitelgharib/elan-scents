create or replace function public.platform_verify_store_delivery(
  p_request_id uuid, p_delivered_at timestamptz, p_evidence_reference text, p_actor uuid default null)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'private', 'pg_temp'
as $function$
