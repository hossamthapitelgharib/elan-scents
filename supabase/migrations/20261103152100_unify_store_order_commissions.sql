create or replace function private.release_due_commissions()
returns integer language plpgsql security definer set search_path to 'public','private','pg_temp' as $function$
declare v_id uuid; v_count integer:=0;
begin
  for v_id in select c.id from public.commissions c where c.status='pending' and c.return_deadline_at is not null
    and c.return_deadline_at<=now() and c.amount>0 order by c.return_deadline_at,c.id for update skip locked loop
    update public.commissions set status='payable',updated_at=now() where id=v_id and status='pending' and return_deadline_at<=now() and amount>0;
    if found then perform private.notify_commission_claim(v_id); v_count:=v_count+1; end if;
  end loop;
  return v_count;
end;$function$;

