const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const migrationDir = path.join(root, 'supabase', 'migrations');
const migrationName = fs.readdirSync(migrationDir).find(name => name.endsWith('_guest_identity_revocation_barrier.sql'));
const migration = migrationName ? fs.readFileSync(path.join(migrationDir, migrationName), 'utf8') : '';
const api = fs.readFileSync(path.join(root, 'api', 'guest-cart.js'), 'utf8');
const consent = fs.readFileSync(path.join(root, 'consent.js'), 'utf8');
const identity = fs.readFileSync(path.join(root, 'guest-identity.js'), 'utf8');
const sqlTest = fs.readFileSync(path.join(__dirname, 'guest-identity-revocation.test.sql'), 'utf8');

function definition(name) {
  const needle = `create function public.${name}(`;
  const start = migration.lastIndexOf(needle);
  assert.notEqual(start, -1, `missing gated wrapper for public.${name}`);
  const end = migration.indexOf('$$;', start);
  assert.notEqual(end, -1, `unterminated wrapper for public.${name}`);
  return migration.slice(start, end + 3);
}

test('refusal gate migration is a single reversible-recorded transaction and stores only HMAC suppressions', () => {
  assert.ok(migrationName, 'migration source exists');
  assert.match(migration, /^begin;/m);
  assert.match(migration, /^commit;/m);
  assert.match(migration, /create table private\.guest_identity_blocks/);
  assert.match(migration, /fingerprint_hash text primary key check \(fingerprint_hash ~ '\^\[a-f0-9\]\{64\}\$'\)/);
  assert.match(migration, /analytics_hash text not null unique/);
  assert.match(migration, /reason in \('refused', 'claimed'\)/);
  assert.match(migration, /interval '24 hours'/);
  assert.doesNotMatch(migration, /visitor_key|raw_fingerprint|browser_uuid/i);
  assert.match(migration, /revoke all on table private\.guest_identity_blocks from public, anon, authenticated, service_role/);
  assert.match(migration, /guest_identity_is_blocked[\s\S]*?language plpgsql\s+volatile/);
  assert.match(migration, /VOLATILE is intentional[\s\S]*?fresh snapshot/i);
});

test('all guest write paths acquire the common advisory lock before checking refusal', () => {
  const mustGate = [
    'resolve_guest_browser', 'save_guest_browser_cart', 'merge_guest_browser', 'claim_guest_browser_cart',
    'record_customer_session', 'record_customer_product_event', 'record_customer_search',
    'record_guest_product_activity', 'guest_signal_store', 'guest_identity_link', 'guest_identity_link_many',
    'guest_signal_behavior'
  ];
  for (const name of mustGate) {
    const body = definition(name);
    assert.match(body, /guest_identity_lock/, `${name} takes the shared lock`);
    assert.match(body, /guest_identity_is_blocked/, `${name} checks the suppression marker`);
    assert.ok(body.indexOf('guest_identity_lock') < body.indexOf('guest_identity_is_blocked'), `${name} checks after locking`);
    assert.match(body, /_pre_barrier_20261114/, `${name} preserves the prior validated implementation`);
  }
  const forget = definition('forget_guest_browser');
  const forgetCall = forget.lastIndexOf('return public.forget_guest_browser_pre_barrier_20261114');
  assert.ok(forget.indexOf('guest_identity_lock') < forget.indexOf('insert into private.guest_identity_blocks'));
  assert.ok(forget.indexOf('insert into private.guest_identity_blocks') < forgetCall);
  const purge = definition('purge_expired_guest_fingerprints');
  assert.match(purge, /delete from private\.guest_identity_blocks where expires_at <= clock_timestamp\(\)/);
  assert.doesNotMatch(migration, /cron\.schedule/i, 'the existing 400-day job is reused; no new schedule is added');
});

test('the browser stores refusal when localStorage works, falls back to a first-party cookie, and retries across tabs', () => {
  assert.match(consent, /REFUSAL_COOKIE = 'elan_consent_refused'/);
  assert.match(consent, /REFUSAL_COOKIE_AGE = 34560000/);
  assert.match(consent, /document\.cookie = REFUSAL_COOKIE/);
  assert.match(consent, /window\.addEventListener\('focus', syncRefusal\)/);
  assert.match(consent, /visibilitychange[\s\S]*?syncRefusal/);
  assert.match(consent, /storage'[\s\S]*?erase\(false\)/);
  assert.match(identity, /body\.blocked === true[\s\S]*?clearKey\(\)/);
  assert.match(identity, /Promise\.all\(\[saveQueue[\s\S]*?identification/);
  assert.match(identity, /e\.newValue === null[\s\S]*?window\.location\.reload\(\)/);
  assert.doesNotMatch(identity, /Math\.random\(\)/, 'identity keys are never generated by a predictable PRNG');
});

test('the API expires the HttpOnly key after claim and never creates a new cookie for blocked identities', () => {
  const claimAt = api.indexOf("const response = await admin('rpc/claim_guest_browser_cart'");
  assert.notEqual(claimAt, -1, 'the claim RPC exists');
  const claim = api.slice(claimAt);
  assert.match(api, /const keys = \[\.\.\.new Set\([\s\S]*?\)\)\]\.sort\(\)/);
  assert.match(api, /merge\.reason === 'blocked'[\s\S]*?expireKeyCookie/);
  assert.match(api, /profile && profile\.blocked === true[\s\S]*?expireKeyCookie/);
  assert.match(claim, /claim_guest_browser_cart[\s\S]*?expireKeyCookie\(req, res\)/);
  assert.ok(api.indexOf('const profile = await response.json()') < api.indexOf("if (action === 'resolve' && shouldSetKeyCookie) setKeyCookie"), 'the key cookie is set only after server-side resolve succeeds');
});

test('database integration test uses synthetic identities and always rolls back', () => {
  assert.match(sqlTest, /^begin;/m);
  assert.match(sqlTest, /^rollback;/m);
  assert.doesNotMatch(sqlTest, /^commit;/mi);
  for (const tableOrRoutine of [
    'resolve_guest_browser', 'save_guest_browser_cart', 'forget_guest_browser', 'merge_guest_browser',
    'claim_guest_browser_cart', 'record_customer_session', 'record_customer_product_event',
    'record_customer_search', 'record_guest_product_activity', 'guest_signal_store',
    'guest_identity_link_many', 'private.guest_identity_blocks', 'auth.users'
  ]) assert.ok(sqlTest.includes(tableOrRoutine), `SQL fixture covers ${tableOrRoutine}`);
  assert.match(sqlTest, /example\.invalid/);
  assert.match(sqlTest, /synthetic/);
});
